#!/bin/bash
# Phase 4.3-4.4 on A: bitcoin.conf, unit, bcli/mine helpers, start.
set -euo pipefail
export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
cat > /var/lib/bitcoind/bitcoin.conf <<'EOF'
regtest=1
server=1
txindex=1
fallbackfee=0.0001
zmqpubrawblock=tcp://10.10.0.1:28332
zmqpubrawtx=tcp://10.10.0.1:28333

[regtest]
rpcbind=127.0.0.1
rpcbind=10.10.0.1
rpcallowip=127.0.0.1
rpcallowip=10.10.0.0/24
EOF
grep '^rpcauth=' /etc/lnmesh/rpcauth.txt >> /var/lib/bitcoind/bitcoin.conf   # generated by 04-bitcoind-install.sh
chown bitcoin:bitcoin /var/lib/bitcoind/bitcoin.conf; chmod 600 /var/lib/bitcoind/bitcoin.conf
install -m 644 /tmp/bitcoind.service /etc/systemd/system/bitcoind.service
cat > /usr/local/bin/bcli <<'EOF'
#!/bin/bash
exec sudo -u bitcoin /usr/local/bin/bitcoin-cli -datadir=/var/lib/bitcoind "$@"
EOF
cat > /usr/local/bin/mine <<'EOF'
#!/bin/bash
# mine N blocks (default 1) to the address stored in /etc/lnmesh/mine.addr
exec /usr/local/bin/bcli generatetoaddress "${1:-1}" "$(cat /etc/lnmesh/mine.addr)" >/dev/null && echo "mined ${1:-1}, height $(/usr/local/bin/bcli getblockcount)"
EOF
chmod 755 /usr/local/bin/bcli /usr/local/bin/mine
systemctl daemon-reload
systemctl enable bitcoind >/dev/null 2>&1
systemctl restart bitcoind
for i in $(seq 1 30); do bcli getblockchaininfo >/dev/null 2>&1 && break; sleep 1; done
systemctl is-active bitcoind
bcli getblockchaininfo | jq -c '{chain, blocks}'
ss -ltnp | grep -E '18443|2833[23]' | awk '{print $4}'
